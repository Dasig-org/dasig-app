// Privacy a coordinator controls: an invite-only group, private work, an approval link, and a lead accepting.
import { chromium } from "playwright-core";
const APP = "http://localhost:8099";
const b = await chromium.launch({ channel: "chrome" });
const ctx = async () => (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage();
const errs = [];
const tap = (p, t) => p.getByText(t, { exact: true }).filter({ visible: true }).first().click();
const log = (...a) => console.log("•", ...a);
const shot = (p, n) => p.screenshot({ path: `/tmp/e2e/${n}.png` });
const don = await ctx(); don.on("pageerror", (e) => errs.push(e.message));
await don.goto(APP + "/"); await tap(don, "Skip"); await don.getByLabel("Your nickname").fill("Don"); await tap(don, "Continue");
await don.getByText("Tell us about you").waitFor(); await tap(don, "Continue"); await tap(don, "I run a group");
await don.getByPlaceholder("e.g. Lahug Uplands Runners Club").fill("Cebu Meetup (test)");
await tap(don, "Next: how it's run"); await don.waitForTimeout(1200); if (await don.getByText("Is this your group?").isVisible().catch(() => false)) await tap(don, "No, ours is a different group"); await tap(don, "Our group and people we invite"); await shot(don, "p-start");
await tap(don, "Create the group"); await tap(don, "Start a project");
await don.getByPlaceholder(/e\.g\./).first().fill("Meetup 12");
await don.getByText("Your group's setting doesn't allow this").waitFor(); log("project can't be more open than its group");
await don.getByText(/^Keep these \d+ teams$/).click(); await don.getByText("Ask someone to lead").first().waitFor();
await don.getByText("Communications", { exact: true }).click(); await don.getByText("You lead it").waitFor().catch(() => {});
await don.getByPlaceholder("Add something to do").fill("Bring chairs"); await don.getByPlaceholder("Add something to do").press("Enter");
await don.getByText("Bring chairs").click(); await tap(don, "Plan this task");
await don.getByText(/isn't public\. Invite volunteers with a link instead/).waitFor(); log("'Anyone can help' is off in a private project"); await shot(don, "p-task");
await don.goBack(); await don.goBack(); await don.getByText("Communications", { exact: true }).click();
await don.getByLabel("Invite people").first().click(); await tap(don, "Nothing about it"); await tap(don, "I approve each person"); await shot(don, "p-invite"); await tap(don, "Make the invite");
const invite = await don.getByText(/\/join\//).textContent(); log("approval link made");
const mia = await ctx(); mia.on("pageerror", (e) => errs.push(e.message));
await mia.goto(invite.replace("https://bayanihan.dasig.org", APP));
await mia.getByText("You're invited to a group on Dasig").waitFor(); log("the link shows nothing about the group");
await mia.getByPlaceholder("e.g. Mia").fill("Mia"); await tap(mia, "Join the team");
await mia.getByText(/Your request was sent/).waitFor(); log("Mia's request is waiting"); await shot(mia, "p-sent");
await don.reload(); await don.getByText("Asking to join").waitFor(); await shot(don, "p-asking"); await tap(don, "Accept");
await don.getByText(/Mia joined Communications/).waitFor(); log("the lead accepted Mia");
console.log("page errors:", errs.length ? errs : "none"); await b.close();
