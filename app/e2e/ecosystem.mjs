import { chromium } from "playwright-core";
const APP = "http://localhost:8099";
const b = await chromium.launch({ channel: "chrome" });
const p = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage();
const errs = []; p.on("pageerror", (e) => errs.push(e.message));
const tap = (t) => p.getByText(t, { exact: true }).filter({ visible: true }).first().click();
const log = (...a) => console.log("•", ...a);
await p.goto(APP + "/"); await tap("Skip");
await p.getByLabel("Your nickname").fill("Rhea"); await tap("Continue");
await p.getByText("Tell us about you").waitFor(); await tap("Continue"); await tap("I run a group");
await p.getByPlaceholder("e.g. Lahug Uplands Runners Club").fill("Group on this device"); await tap("Next"); await tap("Next: how it's run"); await p.waitForTimeout(1200); if (await p.getByText("Is this your group?").isVisible().catch(() => false)) await tap("No, ours is a different group"); await tap("Create the group");
await p.getByText("Bring your people in").waitFor(); log("a group on the device's own server");
await p.goto(APP + "/network"); await p.getByText("Try the Dasig Ecosystem").waitFor();
await p.screenshot({ path: "/tmp/e2e/eco-before.png", fullPage: true });
await tap("Connect to the Dasig Ecosystem");
await p.getByText("In use").nth(0).waitFor(); await p.getByText("Go back to this phone's records").waitFor();
await p.getByLabel(/Ecosystem · up to date/).first().waitFor(); log("connected; sync mark says Ecosystem · up to date");
await p.screenshot({ path: "/tmp/e2e/eco-after.png", fullPage: true });
await p.goto(APP + "/groups"); await p.getByText("Your groups").waitFor();
const seesOld = await p.getByText("Group on this device").count(); log("old group hidden online (fresh start):", seesOld === 0);
await p.goto(APP + "/start-group"); await p.getByPlaceholder("e.g. Lahug Uplands Runners Club").fill("Group on the Ecosystem"); await tap("Next"); await tap("Next: how it's run"); await p.waitForTimeout(1200); if (await p.getByText("Is this your group?").isVisible().catch(() => false)) await tap("No, ours is a different group"); await tap("Create the group");
await p.getByText("Bring your people in").waitFor(); log("created a group on the Ecosystem");
await p.goto(APP + "/network"); await tap("Go back to this phone's records"); await p.getByText("Try the Dasig Ecosystem").waitFor();
await p.goto(APP + "/groups"); await p.getByText("Group on this device").waitFor(); log("back on the device: its group is there");
console.log("page errors:", errs.length ? errs : "none"); await b.close();
