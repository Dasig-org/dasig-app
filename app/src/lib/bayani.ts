/*
 * Bayani in the app (bayani repo: docs/CONTEXT_PACK.md, knowledge/README.md).
 * - Facts: looked up and shown as written, on every phone and the web. Never generated by the model.
 * - The model: Bayani-1 (SmolLM2-1.7B Q4 + the Bayani LoRA add-on), native Android/iOS only, an optional download.
 *   It was trained on BIX records, not on text. It is not a chat model and never writes open answers (Don, 2026-11-15).
 *   It makes judgments about BIX records, held to a fixed set of answers by a grammar. The copilot (lib/copilot.ts)
 *   turns records, rules and those judgments into moves.
 */

void parseFacts;
export const facts = FACTS as Fact[];
/** The best facts for a question; a weak match is not an answer. */
export function ask(question: string) {
  const found = findFacts(question, facts, 3);
  return found.filter((f) => f.score >= Math.max(3, (found[0]?.score ?? 0) * 0.6));
}

const HF = "https://huggingface.co/dasig/bayani-1/resolve/main";
const FILES = { base: { name: "base-q4_k_m.gguf", mb: 1056 }, lora: { name: "bayani-1-lora.gguf", mb: 36 } } as const;
type Key = keyof typeof FILES;
const ORDER: Key[] = ["lora", "base"];
export const MODEL_MB = FILES.base.mb + FILES.lora.mb;
export const modelSupported = Platform.OS !== "web";

/*
 * The model on this phone, one for the whole app (device pass v0.19, 2026-11-16: "Bayani does not work"; "progress
 * shouldn't be lost if I leave the Ask Bayani screen").
 * Before: the download lived in the Ask Bayani screen. Leaving it kept the download running but forgot it; coming back
 * showed "Download" again, and tapping it deleted the file the first download was still writing. A file at 90% of its
 * size counted as downloaded, so a damaged model could be "on this phone" and then fail to load, and every error was
 * swallowed: nothing ever showed, anywhere.
 * Now:
 *  - One download for the app, outside any screen; every screen shows the same progress (useModel). It goes on when
 *    you leave the screen or put the app away. If Android stops the app, it continues from where it stopped (a Range
 *    request; Android's resumable download appends) the next time the app opens on Wi-Fi, or when you tap Continue.
 *  - A file counts only when it has exactly the size the server gave (complete.json). Files from before this (no
 *    complete.json) still count, and if one fails to load the app says it looks damaged and offers to download again.
 *  - Loading and errors are states the screens show: loading, loaded (with how long it took and which CPU build),
 *    failed (with the reason, Try again).
 *  - The context is set explicitly: one sequence with the whole 2,048-token window (llama.rn defaults to 8 parallel
 *    sequences, which can split the window into pieces smaller than one question).
 */
export type ModelState =
  | { phase: "web" | "checking" | "none" | "ready" | "loading" }
  | { phase: "downloading"; got: number; total: number }
  | { phase: "paused"; got: number; total: number; why: string }
  | { phase: "loaded"; lib?: string; loadMs: number; lastError?: string }
  | { phase: "failed"; error: string; damaged?: boolean };

let state: ModelState = modelSupported ? { phase: "checking" } : { phase: "web" };
const listeners = new Set<() => void>();
const set = (s: ModelState) => { state = s; listeners.forEach((f) => f()); };
const subscribe = (f: () => void) => { listeners.add(f); return () => { listeners.delete(f); }; };
export const modelState = () => state;
/** The model's state, for any screen. Re-renders on download progress, loading, errors. */
export function useModel(): ModelState { return useSyncExternalStore(subscribe, modelState, modelState); }
export const modelReady = (s: ModelState) => s.phase === "ready" || s.phase === "loading" || s.phase === "loaded";

async function fs() {
  const FS = await import("expo-file-system");
  const dir = new FS.Directory(FS.Paths.document, "bayani");
  if (!dir.exists) dir.create({ intermediates: true, idempotent: true });
  return { FS, dir, file: (k: Key) => new FS.File(dir, FILES[k].name) };
}
const sizeOf = (f: { exists: boolean; size?: number | null }) => (f.exists ? f.size ?? 0 : 0);

/** complete.json: each file's size from the server, and the size of each finished file. Absent for older downloads. */
type Marker = { size: Partial<Record<Key, number>>; done: Partial<Record<Key, number>> };
async function readMarker(): Promise<Marker | null> {
  const { FS, dir } = await fs();
  const f = new FS.File(dir, "complete.json");
  if (!f.exists) return null;
  try { const m = JSON.parse(await f.text()) as Marker; return { size: m.size ?? {}, done: m.done ?? {} }; } catch { return { size: {}, done: {} }; }
}
async function writeMarker(m: Marker) {
  const { FS, dir } = await fs();
  const f = new FS.File(dir, "complete.json");
  if (!f.exists) f.create();
  f.write(JSON.stringify(m));
}

/** What's on the phone: complete, or how far a download got. */
async function onPhone(): Promise<{ complete: boolean; got: number; total: number }> {
  const { file } = await fs();
  const m = await readMarker();
  const expected = (k: Key) => m?.size[k] ?? FILES[k].mb * 1_000_000;
  const total = ORDER.reduce((n, k) => n + expected(k), 0);
  const got = ORDER.reduce((n, k) => n + sizeOf(file(k)), 0);
  // Before complete.json (v0.19 and earlier): the old rule, 90% of the size. A damaged one shows when it fails to load.
  const complete = m ? ORDER.every((k) => !!m.done[k] && sizeOf(file(k)) === m.done[k]) : ORDER.every((k) => sizeOf(file(k)) > FILES[k].mb * 900_000);
  return { complete, got, total };
}

export async function modelDownloaded(): Promise<boolean> {
  if (!modelSupported) return false;
  return (await onPhone().catch(() => ({ complete: false }))).complete;
}

const WANT = "dasig.bayani.download"; // "on" while a download should go on (after the app was stopped, it resumes)
let running: Promise<void> | null = null;
let current: { pauseAsync: () => Promise<unknown> } | null = null;
let pausing = false;

/** Looks at the phone and sets the state (not while downloading or loaded). */
export async function refreshModel(): Promise<void> {
  if (!modelSupported || running || ctx || loading) return;
  try {
    const p = await onPhone();
    if (running || ctx || loading) return;
    if (p.complete) { if (state.phase !== "failed") set({ phase: "ready" }); }
    else if (p.got > 0) set({ phase: "paused", got: p.got, total: p.total, why: "Stopped before it finished. It continues from there." });
    else set({ phase: "none" });
  } catch { set({ phase: "none" }); }
}

/** At app start: the state, and a download that was going on continues, on Wi-Fi. */
export async function startModel(): Promise<void> {
  await refreshModel();
  if (state.phase !== "paused" || (await AsyncStorage.getItem(WANT).catch(() => null)) !== "on") return;
  const Net = await import("expo-network");
  const n = await Net.getNetworkStateAsync().catch(() => null);
  if (n?.type === Net.NetworkStateType.WIFI) void downloadModel();
  else if (state.phase === "paused") set({ ...state, why: "Waiting for Wi-Fi. Tap Continue to use mobile data." });
}

/**
 * Download both files (about 1.1 GB). Safe to call from anywhere and more than once: there is one download. Progress
 * and errors are in the state (useModel); the promise never rejects.
 */
export function downloadModel(): Promise<void> {
  if (!modelSupported) return Promise.resolve();
  if (!running) running = fetchAll().finally(() => { running = null; current = null; });
  return running;
}

async function fetchAll(): Promise<void> {
  pausing = false;
  await AsyncStorage.setItem(WANT, "on").catch(() => {});
  try {
    const { file } = await fs();
    const L = await import("expo-file-system/legacy");
    const old = await readMarker();
    // An older download (no complete.json) is started over: its files can't be checked.
    if (!old) for (const k of ORDER) if (file(k).exists) file(k).delete();
    const m: Marker = old ?? { size: {}, done: {} };
    await writeMarker(m);
    const expected = (k: Key) => m.size[k] ?? FILES[k].mb * 1_000_000;
    const total = () => ORDER.reduce((n, k) => n + expected(k), 0);
    for (const k of ORDER) {
      if (m.done[k] && sizeOf(file(k)) === m.done[k]) continue;
      const before = ORDER.slice(0, ORDER.indexOf(k)).reduce((n, j) => n + expected(j), 0);
      for (let attempt = 0; ; attempt++) {
        const have = sizeOf(file(k));
        // Continue a partial file (Android appends after a Range request); otherwise start it over.
        const resume = Platform.OS === "android" && attempt === 0 && have > 0 && !!m.size[k] && have < m.size[k]! ? String(have) : undefined;
        if (!resume && file(k).exists) file(k).delete();
        set({ phase: "downloading", got: before + (resume ? have : 0), total: total() });
        const dl = L.createDownloadResumable(`${HF}/${FILES[k].name}`, file(k).uri, {}, (p) => {
          if (p.totalBytesExpectedToWrite > 0 && m.size[k] !== p.totalBytesExpectedToWrite) { m.size[k] = p.totalBytesExpectedToWrite; writeMarker(m).catch(() => {}); }
          set({ phase: "downloading", got: before + p.totalBytesWritten, total: total() });
        }, resume);
        current = dl;
        let r: Awaited<ReturnType<typeof dl.downloadAsync>>;
        try { r = await dl.downloadAsync(); } catch (e) { if (pausing) return; throw e; }
        if (pausing) return;
        if (!r) throw new Error("The download stopped.");
        if (r.status >= 400) { if (file(k).exists) file(k).delete(); throw new Error(`The download stopped (${r.status}). Try again on Wi-Fi.`); }
        // A server that ignored the Range request sent the whole file after the part we had: start this file over.
        if (resume && r.status !== 206) { if (attempt === 0) continue; throw new Error("The download couldn't continue. Try again."); }
        const got = sizeOf(file(k));
        if (m.size[k] && got !== m.size[k]) {
          if (attempt === 0) continue; // once more, from the start
          if (file(k).exists) file(k).delete();
          throw new Error("The download was incomplete. Try again on Wi-Fi.");
        }
        m.done[k] = got;
        await writeMarker(m);
        break;
      }
    }
    await AsyncStorage.removeItem(WANT).catch(() => {});
    set({ phase: "ready" });
  } catch (e) {
    const p = await onPhone().catch(() => ({ got: 0, total: MODEL_MB * 1_000_000 }));
    set({ phase: "paused", got: p.got, total: p.total, why: e instanceof Error ? e.message : String(e) });
  }
}

/** Pause; Continue (downloadModel) picks up from where it stopped. */
export async function pauseDownload(): Promise<void> {
  if (!running) return;
  pausing = true;
  await AsyncStorage.removeItem(WANT).catch(() => {});
  await current?.pauseAsync().catch(() => {});
  const p = await onPhone().catch(() => ({ got: 0, total: MODEL_MB * 1_000_000 }));
  set({ phase: "paused", got: p.got, total: p.total, why: "Paused." });
}

export async function removeModel(): Promise<void> {
  if (running) await pauseDownload();
  await AsyncStorage.removeItem(WANT).catch(() => {});
  const c = ctx; ctx = null;
  await (c as unknown as { release?: () => Promise<void> } | null)?.release?.().catch(() => {});
  const { FS, dir, file } = await fs();
  for (const k of ORDER) if (file(k).exists) file(k).delete();
  const m = new FS.File(dir, "complete.json");
  if (m.exists) m.delete();
  cache.clear();
  set({ phase: "none" });
}

type Ctx = {
  completion: (p: Record<string, unknown>, cb?: (d: { token: string }) => void) => Promise<{ text: string; completion_probabilities?: TokenProbs }>;
  stopCompletion: () => Promise<void>;
  release?: () => Promise<void>;
};
let ctx: Ctx | null = null;
let loading: Promise<Ctx | null> | null = null;
const path = (uri: string) => decodeURI(uri.replace(/^file:\/\//, ""));
const message = (e: unknown) => (e instanceof Error ? e.message : String(e)) || "Unknown error";

/** The loaded model, loading it the first time (a few seconds). Null when it isn't on this phone or failed to load. */
async function model(): Promise<Ctx | null> {
  if (ctx) return ctx;
  if (state.phase === "failed") return null; // until Try again (retryModel), so one failure doesn't load it ten times
  if (!loading) loading = load().finally(() => { loading = null; });
  return loading;
}
async function load(): Promise<Ctx | null> {
  if (!(await modelDownloaded())) { await refreshModel(); return null; }
  const t0 = Date.now();
  const legacy = !(await readMarker());
  set({ phase: "loading" });
  try {
    const { file } = await fs();
    const { initLlama } = await import("llama.rn");
    const c = await initLlama({
      model: path(file("base").uri),
      lora_list: [{ path: path(file("lora").uri), scaled: 1 }],
      n_ctx: 2048, n_batch: 512, n_parallel: 1, kv_unified: true, use_mlock: false,
    });
    ctx = c as unknown as Ctx;
    set({ phase: "loaded", lib: (c as { androidLib?: string }).androidLib || undefined, loadMs: Date.now() - t0 });
    return ctx;
  } catch (e) {
    set({ phase: "failed", error: message(e), damaged: legacy || /gguf|magic|tensor|read|truncat|failed to load model/i.test(message(e)) });
    return null;
  }
}
/** After a failure: try loading again on the next question. */
export function retryModel() { if (state.phase === "failed") { set({ phase: "ready" }); cache.clear(); } }
const noteError = (e: unknown) => { if (state.phase === "loaded") set({ ...state, lastError: message(e) }); };

/**
 * A quick check that Bayani-1 works on this phone: load it, and answer one yes/no under a grammar. Says how long each
 * took and which CPU build of llama.cpp the phone uses. Throws with the reason.
 */
export async function checkModel(): Promise<{ loadMs: number; answerMs: number; lib?: string; answer: string }> {
  retryModel();
  const t0 = Date.now();
  const m = await serial(() => model());
  if (!m) throw new Error(state.phase === "failed" ? state.error : "Bayani-1 isn't on this phone yet.");
  const loadMs = Date.now() - t0, t1 = Date.now();
  const r = await serial(() => m.completion({ prompt: chat("Is a clean-up drive something a volunteer group does? Answer yes or no."), n_predict: 3, temperature: 0, grammar: 'root ::= "yes" | "no"', stop: ["<|im_end|>"] }));
  return { loadMs, answerMs: Date.now() - t1, lib: state.phase === "loaded" ? state.lib : undefined, answer: r.text.trim() };
}

