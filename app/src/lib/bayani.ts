export type Judgment =
  | { kind: "yes-no"; value: boolean; confidence: number; question: Question["kind"] }
  | { kind: "reference"; value: string | null; confidence: number; question: Question["kind"] }
  | { kind: "text"; value: string; confidence: number; question: Question["kind"] };

// One question at a time: the phone has one model context. Answers are kept for the same records (by version).
let queue: Promise<unknown> = Promise.resolve();
const serial = <T,>(f: () => Promise<T>): Promise<T> => { const run = queue.then(f, f); queue = run.catch(() => undefined); return run; };
const cache = new Map<string, Judgment | null>();
const keyOf = (q: Question, records: R[]) => JSON.stringify(q) + "|" + records.map((r) => `${r.resourceType}/${r.id}@${r.meta?.version ?? 0}`).sort().join(",");

/**
 * One of the six questions Bayani-1 was trained on (bayani README, "The questions Bayani-1 is trained on"), asked in
 * exactly the training format: the pack is built by the bayani package from BIX records (`buildPack`), so the app and
 * the training data can't drift apart. Fixed answers are held to the allowed list by a grammar; the confidence is the
 * raw softmax over the answer's tokens (`post_sampling_probs: false`). A general title is the only text, under a
 * grammar, at most 60 characters. Null when the model isn't on this phone, or when the answer is known without it.
 * An answer is kept for the same records; a failure isn't (so it's asked again), and shows in the model's state.
 * `records`: what this person's server gave them (already filtered for them, rule 26), including the project, its
 * teams, its steps and the group's Practices.
 */
export async function judge(q: Question, records: R[], viewer: string): Promise<Judgment | null> {
  if (!modelSupported) return null;
  const key = keyOf(q, records);
  if (cache.has(key)) return cache.get(key)!;
  let pack: Pack;
  try { pack = buildPack(q, { records: records as never, viewer, now: new Date().toISOString(), prefiltered: true, maxTokens: 600 }); } catch { return null; }
  if (!pack.needsModel) return null;
  const out = await serial(async (): Promise<Judgment | null | undefined> => {
    const m = await model();
    if (!m) return undefined;
    const r = await m.completion(completionFor(pack));
    const d = decode(pack, r.text);
    if (!d.ok) return null;
    return { ...d, confidence: confidenceOf(pack, r.completion_probabilities), question: q.kind } as Judgment;
  }).catch((e) => { noteError(e); return undefined; });
  if (out !== undefined) cache.set(key, out);
  return out ?? null;
}
/** How a person's answer to a model suggestion is recorded (BIX "Suggestions and their answers"). */
export const assisted = (j: Judgment, edited = false) => ({ type: "model" as const, model: { ...MODEL, question: j.question, ...(Number.isFinite(j.confidence) ? { confidence: Math.round(j.confidence * 100) / 100 } : {}), ...(edited ? { edited: true } : {}) } });

/** The existing step most likely to be the same as a usual one: shared words, plus a point for the same team. */
export function closestTask(practice: R, tasks: R[], teamName: (t: R) => string | undefined): R | null {
  const pw = words(String(practice.title ?? ""));
  let best: R | null = null, score = 0;
  for (const t of tasks) {
    if (t.status === "cancelled") continue;
    const shared = [...words(String(t.title ?? ""))].filter((w) => pw.has(w)).length;
    const s = shared * 2 + (String(teamName(t) ?? "").toLowerCase() === String(practice.team ?? "").toLowerCase() && practice.team ? 1 : 0);
    if (s > score) { score = s; best = t; }
  }
  return best;
}
